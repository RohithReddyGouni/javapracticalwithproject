CREATE TABLE payment_attempts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    attempt_key UUID NOT NULL,
    booking_id BIGINT NOT NULL,
    expected_amount_minor BIGINT NOT NULL,
    currency VARCHAR(3) NOT NULL,
    status VARCHAR(40) NOT NULL,
    stripe_session_id VARCHAR(255),
    stripe_payment_intent_id VARCHAR(255),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL,

    CONSTRAINT uk_payment_attempt_key
        UNIQUE (attempt_key),

    CONSTRAINT fk_payment_attempt_booking
        FOREIGN KEY (booking_id) REFERENCES bookings(id),

    CONSTRAINT uk_payment_attempt_session
        UNIQUE (stripe_session_id),

    CONSTRAINT uk_payment_attempt_intent
        UNIQUE (stripe_payment_intent_id),

    CONSTRAINT chk_payment_attempt_amount
        CHECK (expected_amount_minor > 0),

    CONSTRAINT chk_payment_attempt_currency
        CHECK (currency = 'USD'),

    CONSTRAINT chk_payment_attempt_status
        CHECK (status IN (
            'INITIATED',
            'CHECKOUT_CREATED',
            'SUCCEEDED',
            'FAILED',
            'RECONCILIATION_REQUIRED',
            'REFUND_PENDING',
            'REFUNDED'
        ))
);

CREATE INDEX idx_payment_attempt_booking_id
    ON payment_attempts (booking_id);