CREATE TABLE refund_requests (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    refund_key UUID NOT NULL,
    payment_attempt_id BIGINT NOT NULL,
    amount_minor BIGINT NOT NULL,
    currency VARCHAR(3) NOT NULL,
    status VARCHAR(40) NOT NULL DEFAULT 'PENDING',
    stripe_refund_id VARCHAR(255),
    attempts INTEGER NOT NULL DEFAULT 0,
    next_attempt_at TIMESTAMP WITH TIME ZONE NOT NULL,
    lease_until TIMESTAMP WITH TIME ZONE,
    lease_token UUID,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
    last_error_code VARCHAR(120),

    CONSTRAINT uk_refund_request_key
        UNIQUE (refund_key),

    CONSTRAINT uk_refund_payment_attempt
        UNIQUE (payment_attempt_id),

    CONSTRAINT uk_refund_stripe_id
        UNIQUE (stripe_refund_id),

    CONSTRAINT fk_refund_payment_attempt
        FOREIGN KEY (payment_attempt_id)
        REFERENCES payment_attempts(id),

    CONSTRAINT chk_refund_amount
        CHECK (amount_minor > 0),

    CONSTRAINT chk_refund_currency
        CHECK (currency = 'USD'),

    CONSTRAINT chk_refund_attempts
        CHECK (attempts >= 0),

    CONSTRAINT chk_refund_status
        CHECK (status IN (
            'PENDING',
            'PROCESSING',
            'SUCCEEDED',
            'RECONCILIATION_REQUIRED',
            'FAILED'
        ))
);

CREATE INDEX idx_refund_requests_pending
    ON refund_requests (next_attempt_at)
    WHERE status = 'PENDING';

CREATE INDEX idx_refund_requests_processing
    ON refund_requests (lease_until)
    WHERE status = 'PROCESSING';