CREATE TABLE bookings (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    room_id BIGINT NOT NULL,
    check_in_date DATE NOT NULL,
    check_out_date DATE NOT NULL,
    rooms_count INTEGER NOT NULL,
    guests_per_room INTEGER NOT NULL,
    total_price NUMERIC(14, 2) NOT NULL,
    status VARCHAR(20) NOT NULL,
    reserved_until TIMESTAMP WITH TIME ZONE NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,

    CONSTRAINT fk_bookings_user
        FOREIGN KEY (user_id) REFERENCES users(id),

    CONSTRAINT fk_bookings_room
        FOREIGN KEY (room_id) REFERENCES rooms(id),

    CONSTRAINT chk_bookings_dates
        CHECK (check_out_date > check_in_date),

    CONSTRAINT chk_bookings_rooms_count
        CHECK (rooms_count > 0),

    CONSTRAINT chk_bookings_guests_per_room
        CHECK (guests_per_room > 0),

    CONSTRAINT chk_bookings_total_price
        CHECK (total_price > 0),

    CONSTRAINT chk_bookings_status
        CHECK (status IN (
            'RESERVED', 'CONFIRMED', 'CANCELLED', 'EXPIRED'
        )),

    CONSTRAINT chk_bookings_hold
        CHECK (reserved_until > created_at)
);

CREATE INDEX idx_bookings_user_id
    ON bookings (user_id);

CREATE INDEX idx_bookings_room_id
    ON bookings (room_id);

CREATE INDEX idx_bookings_status_reserved_until
    ON bookings (status, reserved_until);