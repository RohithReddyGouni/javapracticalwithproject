CREATE TABLE inventory (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    room_id BIGINT NOT NULL,
    date DATE NOT NULL,
    total_count INTEGER NOT NULL,
    booked_count INTEGER NOT NULL DEFAULT 0,
    reserved_count INTEGER NOT NULL DEFAULT 0,
    price NUMERIC(10, 2) NOT NULL,

    CONSTRAINT fk_inventory_room
        FOREIGN KEY (room_id) REFERENCES rooms(id),

    CONSTRAINT uk_inventory_room_date
        UNIQUE (room_id, date),

    CONSTRAINT chk_inventory_total_count
        CHECK (total_count >= 0),

    CONSTRAINT chk_inventory_booked_count
        CHECK (booked_count >= 0),

    CONSTRAINT chk_inventory_reserved_count
        CHECK (reserved_count >= 0),

    CONSTRAINT chk_inventory_capacity
        CHECK (booked_count + reserved_count <= total_count),

    CONSTRAINT chk_inventory_price
        CHECK (price > 0)
);