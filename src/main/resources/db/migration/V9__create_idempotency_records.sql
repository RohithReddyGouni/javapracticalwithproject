CREATE TABLE idempotency_records (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    operation VARCHAR(80) NOT NULL,
    request_key VARCHAR(100) NOT NULL,
    request_hash VARCHAR(64) NOT NULL,
    status VARCHAR(20) NOT NULL,
    booking_id BIGINT,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,

    CONSTRAINT fk_idempotency_user
        FOREIGN KEY (user_id) REFERENCES users(id),

    CONSTRAINT fk_idempotency_booking
        FOREIGN KEY (booking_id) REFERENCES bookings(id),

    CONSTRAINT uk_idempotency_request
        UNIQUE (user_id, operation, request_key),

    CONSTRAINT chk_idempotency_status
        CHECK (status IN ('IN_PROGRESS', 'COMPLETED')),

    CONSTRAINT chk_idempotency_completed_booking
        CHECK (status <> 'COMPLETED' OR booking_id IS NOT NULL)
);