CREATE TABLE hotels (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(255),
    city VARCHAR(255),
    active BOOLEAN NOT NULL
);

CREATE TABLE rooms (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    type VARCHAR(255),
    base_price NUMERIC(10, 2) NOT NULL,
    total_count INTEGER,
    capacity INTEGER,
    hotel_id BIGINT NOT NULL,
    CONSTRAINT fk_rooms_hotel
        FOREIGN KEY (hotel_id) REFERENCES hotels(id)
);